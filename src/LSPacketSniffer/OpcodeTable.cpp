const wchar_t* LookupOpcodeName(DWORD dwID)
{
	int lo = 0, hi = (int)g_OpcodeCount - 1;
	while (lo <= hi)
	{
		int mid = (lo + hi) / 2;
		if (g_OpcodeTable[mid].dwID == dwID)
			return g_OpcodeTable[mid].szName;
		if (g_OpcodeTable[mid].dwID < dwID)
			lo = mid + 1;
		else
			hi = mid - 1;
	}
	return nullptr;
}

std::wstring OpcodeNameOrHex(DWORD dwID)
{
	const wchar_t* p = LookupOpcodeName(dwID);
	if (p) return p;
	wchar_t buf[16];
	swprintf_s(buf, L"0x%04X", dwID);
	return buf;
}

const wchar_t* OpcodeFamily(DWORD dwID)
{
	const wchar_t* p = LookupOpcodeName(dwID);
	if (!p) return nullptr;
	if (wcsncmp(p, L"CTPK_", 5) == 0) return L"C->S";
	if (wcsncmp(p, L"STPK_", 5) == 0) return L"S->C";
	if (wcsncmp(p, L"CUPK_", 5) == 0) return L"C->S UDP";
	if (wcsncmp(p, L"SUPK_", 5) == 0) return L"S->C UDP";
	if (wcsncmp(p, L"LUPK_", 5) == 0) return L"UDP misc";
	return L"inter-server";
}
