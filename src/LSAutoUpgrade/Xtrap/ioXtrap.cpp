ioXtrap &ioXtrap::GetInstance()
{
	if( sg_Instance == NULL )
	{
		sg_Instance = new ioXtrap;
#ifdef SRC_NA
		CString szINIPath = "info\\";
		szINIPath += "autoupgrade_info_mgame.ini";
		ioINILoaderAU kIniLoder( (LPCTSTR) szINIPath );
		kIniLoder.SetTitle("autoupgrade_info");
		m_bQA = kIniLoder.LoadBool("QA", false);
		//LOG.PrintTimeAndLog( 0, "QA : %d",m_bQA);
#endif
	}

	return (*sg_Instance);
}

void ioXtrap::ReleaseInstance()
{
	if( sg_Instance)
		delete sg_Instance;

	sg_Instance = NULL;
}